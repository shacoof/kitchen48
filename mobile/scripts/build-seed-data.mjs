#!/usr/bin/env node
// Build-time codegen: reads recipe export folders and emits
//   - mobile/assets/seed-recipes/<slug>/hero.jpg   (copied from export)
//   - mobile/src/seed/seed-recipes.ts              (typed static data + require() for images)
//
// Usage:
//   node scripts/build-seed-data.mjs [--source /path/to/export]
//
// Default source: $HOME/kitchen48-recipe-export

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MOBILE_ROOT = path.resolve(__dirname, '..');

const argv = process.argv.slice(2);
const sourceIdx = argv.indexOf('--source');
const SOURCE_DIR = sourceIdx >= 0
  ? argv[sourceIdx + 1]
  : path.join(os.homedir(), 'kitchen48-recipe-export');

const ASSETS_OUT = path.join(MOBILE_ROOT, 'assets', 'seed-recipes');
const CODE_OUT = path.join(MOBILE_ROOT, 'src', 'seed', 'seed-recipes.ts');

function listRecipeDirs(root) {
  return fs.readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

function readYaml(dir) {
  const yamlPath = path.join(dir, 'kitchen48-recipe.yaml');
  const raw = fs.readFileSync(yamlPath, 'utf8');
  return parseYaml(raw);
}

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function copyHero(srcDir, slug, heroName) {
  if (!heroName) return null;
  const src = path.join(srcDir, heroName);
  if (!fs.existsSync(src)) return null;
  const ext = path.extname(heroName) || '.jpg';
  const destDir = path.join(ASSETS_OUT, slug);
  ensureDir(destDir);
  const destName = `hero${ext}`;
  const dest = path.join(destDir, destName);
  fs.copyFileSync(src, dest);
  return destName;
}

function jsonEscape(value) {
  return JSON.stringify(value);
}

function emitSteps(steps) {
  if (!steps || steps.length === 0) return '    steps: [],';
  const sorted = [...steps].sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
  const lines = sorted.map((s) => {
    const ingredients = (s.ingredients ?? []).map((ing) => ({
      name: ing.name,
      quantity: ing.quantity ?? null,
      unit: ing.unit ?? null,
    }));
    return `      {
        order: ${Number(s.order ?? 0)},
        title: ${jsonEscape(s.title ?? null)},
        instruction: ${jsonEscape(s.instruction ?? null)},
        prepTime: ${s.prepTime ?? null},
        prepTimeUnit: ${jsonEscape(s.prepTimeUnit ?? 'MINUTES')},
        waitTime: ${s.waitTime ?? null},
        waitTimeUnit: ${jsonEscape(s.waitTimeUnit ?? 'MINUTES')},
        ingredients: ${JSON.stringify(ingredients)},
      }`;
  });
  return `    steps: [
${lines.join(',\n')},
    ],`;
}

function emitRecipe(slug, data, heroAssetName) {
  const heroRequire = heroAssetName
    ? `require('../../assets/seed-recipes/${slug}/${heroAssetName}')`
    : 'null';
  return `  {
    slug: ${jsonEscape(slug)},
    title: ${jsonEscape(data.title)},
    description: ${jsonEscape(data.description ?? null)},
    servings: ${data.servings ?? null},
    measurementSystem: ${jsonEscape(data.measurementSystem ?? 'metric')},
    difficulty: ${jsonEscape(data.difficulty ?? null)},
    cuisine: ${jsonEscape(data.cuisine ?? null)},
    mealType: ${jsonEscape(data.mealType ?? null)},
    isPublished: ${data.isPublished === true},
    dietaryTags: ${JSON.stringify(data.dietaryTags ?? [])},
    heroImageAsset: ${heroRequire},
${emitSteps(data.steps)}
  }`;
}

function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error(`Source directory not found: ${SOURCE_DIR}`);
    process.exit(1);
  }

  // Clean old generated assets so removals propagate.
  if (fs.existsSync(ASSETS_OUT)) {
    fs.rmSync(ASSETS_OUT, { recursive: true, force: true });
  }
  ensureDir(ASSETS_OUT);
  ensureDir(path.dirname(CODE_OUT));

  const slugs = listRecipeDirs(SOURCE_DIR);
  const recipes = [];
  for (const slug of slugs) {
    const dir = path.join(SOURCE_DIR, slug);
    let data;
    try {
      data = readYaml(dir);
    } catch (err) {
      console.warn(`Skipping ${slug}: ${err.message}`);
      continue;
    }
    const heroAssetName = copyHero(dir, slug, data.heroImage);
    recipes.push(emitRecipe(slug, data, heroAssetName));
    console.log(`  ✓ ${slug}${heroAssetName ? '' : ' (no hero)'}`);
  }

  const header = `// AUTO-GENERATED by scripts/build-seed-data.mjs. Do not edit by hand.
// Regenerate with: node scripts/build-seed-data.mjs

export interface SeedIngredient {
  name: string;
  quantity: number | null;
  unit: string | null;
}

export interface SeedStep {
  order: number;
  title: string | null;
  instruction: string | null;
  prepTime: number | null;
  prepTimeUnit: string;
  waitTime: number | null;
  waitTimeUnit: string;
  ingredients: SeedIngredient[];
}

export interface SeedRecipe {
  slug: string;
  title: string;
  description: string | null;
  servings: number | null;
  measurementSystem: string;
  difficulty: string | null;
  cuisine: string | null;
  mealType: string | null;
  isPublished: boolean;
  dietaryTags: string[];
  heroImageAsset: number | null;
  steps: SeedStep[];
}

export const SEED_SCHEMA_VERSION = 1;

export const SEED_RECIPES: SeedRecipe[] = [
`;

  const body = recipes.join(',\n') + ',\n';
  const footer = `];\n`;

  fs.writeFileSync(CODE_OUT, header + body + footer);
  console.log(`\nWrote ${recipes.length} recipes to ${path.relative(MOBILE_ROOT, CODE_OUT)}`);
  console.log(`Assets copied to ${path.relative(MOBILE_ROOT, ASSETS_OUT)}/`);
}

main();
